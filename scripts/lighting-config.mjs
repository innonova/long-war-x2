// The light of the missions on Enemy Within's maps (features/lw-missions.md): LongWarX2/Config/XComMaps.ini, from the mod's
// XComLWEWMaps.ini (scripts/maps-config.mjs: each map's Night, as Long War's DefaultMaps.ini has it). Long War X2's plot
// type gets a clear day of its own (never rain, no heavy weather fog); an EW night map's plot (LWX2_<map>) gets XCOM 2's
// night instead, its city night for EW's town maps (URB_), its nature night for the rest: XCOM 2's lighting manager takes a
// plot map's own lighting over its plot type's (XComEnvLightingManager.GetMatchingEnvLightingDefs).
//   node scripts/lighting-config.mjs > LongWarX2/Config/XComMaps.ini
import { readFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const ini = readFileSync(join(dirname(fileURLToPath(import.meta.url)), '..', 'LongWarX2', 'Config', 'XComLWEWMaps.ini'), 'utf8')
const night = [...new Set([...ini.matchAll(/^\+Maps=\(Name="([^"]+)".*Night=true/gm)].map((m) => m[1]))]
const urban = night.filter((n) => n.startsWith('URB_'))
const nature = night.filter((n) => !n.startsWith('URB_'))
const plots = (list) => list.map((n, i) => `arrPlotMaps[${i}]="LWX2_${n}"`).join(', ')
console.log(
  [
    '; The light of a mission on an Enemy Within map, generated by scripts/lighting-config.mjs from XComLWEWMaps.ini. Do not',
    "; edit by hand. Long War X2's plot type: a clear day of its own (never rain, no heavy weather fog). EW's night maps' plots:",
    `; XCOM 2's night (${urban.length} town maps its city night, ${nature.length} others its nature night).`,
    '[XComGame.XComEnvLightingManager]',
    '+arrEnvironmentLightingDefs=(MapName="EnvLighting_Day_Arid", eEnvLighting[0]=eEnvLighting_Day, eTimeOfDay=eTimeOfDay_Noon, eMood=eMood_Normal, eWeatherCondition=eWeatherType_Clear, arrPlotTypes[0]="LWX2_EW")',
    `+arrEnvironmentLightingDefs=(MapName="EnvLighting_UrbanNight", eEnvLighting[0]=eEnvLighting_Night, eTimeOfDay=eTimeOfDay_Night, eMood=eMood_Normal, eWeatherCondition=eWeatherType_Clear, ${plots(urban)})`,
    `+arrEnvironmentLightingDefs=(MapName="EnvLighting_NatureNight", eEnvLighting[0]=eEnvLighting_Night, eTimeOfDay=eTimeOfDay_Night, eMood=eMood_Normal, eWeatherCondition=eWeatherType_Clear, ${plots(nature)})`,
  ].join('\r\n'),
)
