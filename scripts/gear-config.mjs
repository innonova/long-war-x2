// Long War's weapons as the mod's config (features/lw-gear.md): LongWarX2/Config/XComLWGear.ini, from the
// player's Long War DefaultGameCore.ini (its Weapons= lines) and the shared rules (lw-gear.mjs): each
// weapon of Long War's soldier families with its numbers, XCOM 2 category (who may carry it), slot,
// look (the XCOM 2 weapon whose model it takes) and tech; the starting kit unlimited. The armours. Then what engineering
// builds (+Builds): each item's cost, days and engineers (ItemBalance_Normal) and what it needs first (the
// Tree's data/itemtree.json, read from Long War's XGItemTree.BuildItems). Numbers only: the names are Long
// War's words, written on the player's machine (lw-words.mjs).
//
//   node scripts/gear-config.mjs <Long War's DefaultGameCore.ini> > LongWarX2/Config/XComLWGear.ini
import { readFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { ARMOURS, CLASS_PROPERTY, FAMILIES, INFINITE, MEC_CLASSES, RANGE, SMALL, STARTING_ARMOUR, TECH, TIERS, equippable, smallTemplate, categoryFor, familyOf, itemTemplate, readArmours, readBalance, readWeapons, startingKit } from './lw-gear.mjs'

const core = readFileSync(process.argv[2], 'latin1')
const treeData = (f) => JSON.parse(readFileSync(join(dirname(fileURLToPath(import.meta.url)), '..', '..', 'xcom-ew-lw-tree', 'data', f), 'utf8'))
const ITEMS = treeData('enums.json').enums.EItemType
const itemTree = new Map(treeData('itemtree.json').items.map((i) => [i.id, i]))
const balance = readBalance(core, ITEMS)
const weapons = readWeapons(core, ITEMS)
const infinite = new Set([...Object.keys(CLASS_PROPERTY).flatMap(startingKit), ...INFINITE])
const out = [
  "; Long War 1.0's soldier weapons, generated by scripts/gear-config.mjs from Long War's DefaultGameCore.ini",
  '; (Weapons=) and scripts/lw-gear.mjs. Do not edit by hand. Item: Long War\'s number; Ammo: shots between',
  '; reloads; Category: the classes that may carry it; Infinite: held without limit (Long War\'s ballistic tier).',
  '[LongWarX2.LWGearRules]',
]
/** A field of an item's BalanceMods_Classic line (Long War's extra weapon and item stats: "iDefense -- defense, works only for
 *  weapons and items; iMobility -- mobility, works only for weapons/items"; XGTacticalGameCore.GetUpgradeAbilities). */
const balanceOf = (id, k) => Number(core.match(new RegExp(`^BalanceMods_Classic=\\(eType=${id},.*?${k}=(-?\\d+)`, 'm'))?.[1] ?? 0)
for (const items of Object.values(FAMILIES)) {
  for (const item of items) {
    if (item === null) continue
    const w = weapons.get(item)
    if (!w) throw new Error(`no Weapons= line for item ${item}`)
    const { family, tier, look } = familyOf(item)
    const secondary = w.props.includes('Pistol')
    const kind = secondary ? 'Pistol' : w.props.includes('MoveLimited') ? 'Sniper' : 'Rifle'
    out.push(
      `+Weapons=(Item=${item}, Enum=${ITEMS[item]}, Family=${family}, Tier=${TIERS[tier]}, Damage=${w.iDamage}, Crit=${w.iCritical}, Aim=${w.iOffenseBonus}, ` +
        `Ammo=${Number(w.iSuppression) % 100}, AmmoConserved=${Math.floor(Number(w.iSuppression) / 100) || Number(w.iSuppression) % 100}, Environment=${w.iEnvironmentDamage ?? 0}, Category=${categoryFor(w.props, item)}, ` +
        `Slot=${secondary ? 'eInvSlot_SecondaryWeapon' : 'eInvSlot_PrimaryWeapon'}, Kind=${kind}, Look=${look}, Tech=${TECH[tier]}, ` +
        `Range=${RANGE[family]}, Infinite=${infinite.has(item)}, Mobility=${balanceOf(item, 'iMobility')}, Defense=${balanceOf(item, 'iDefense')})`,
    )
  }
}

// The armours: HP, defence, will and mobility; grapple and immunities; flight (eAbility_Fly: its fuel, air evasion; ghost
// not yet); the XCOM 2 armour each looks like; those never built (cost -1) unlimited.
const armours = readArmours(core, ITEMS)
// Each item's damage reduction: BalanceMods_Classic's iHP, in tenths ("iHP -- damage reduction, works for weapons/armor/items").
const itemDR = new Map([...core.matchAll(/^BalanceMods_Classic=\(eType=(\d+),.*?iHP=(-?\d+)/gm)].map((m) => [Number(m[1]), Number(m[2]) / 10]))
out.push('; Armors: HP, Defense, Will, Mobility, DR (damage reduction); Look: the XCOM 2 armour whose body parts and images it takes.')
for (const [id, look] of Object.entries(ARMOURS)) {
  const a = armours.get(Number(id))
  if (!a) throw new Error(`no Armors= line for item ${id}`)
  out.push(
    `+Armors=(Item=${id}, Enum=${ITEMS[id]}, HP=${a.iHPBonus}, Defense=${a.iDefenseBonus}, Will=${a.iWillBonus}, Mobility=${a.iMobilityBonus}, ` +
      `SmallItems=${a.iSmallItems}, Look=${look}, Grapple=${a.props.includes('Grapple')}, FireImmune=${a.props.includes('FireImmunity')}, ` +
      `PoisonImmune=${a.props.includes('PoisonImmunity')}, Infinite=${(balance.get(Number(id))?.cash ?? -1) < 0}, DR=${itemDR.get(Number(id)) ?? 0}` +
      (a.abilities.includes('Fly') ? `, Fly=true, Fuel=${a.iFlightFuel ?? 0}, AirEvade=${a.props.includes('AirEvade')}` : '') + ')',
  )
}
out.push(`StartingArmor=${STARTING_ARMOUR}`)
// The small items and the Rocketeer's launcher (lw-gear.mjs SMALL): Long War's numbers from their Weapons= lines.
out.push(
  '; SmallItems: Kind (Grenade, Medikit, Launcher, Rocket, Passive); Look: the XCOM 2 item whose abilities, effects and look it',
  '; takes; Damage, Environment; Radius and Range in tiles; Aim, Crit, HP while carried; Ammo: shots x this; Classes: who may carry it.',
)
const scopeCrit = Number(core.match(/^FOUNDRY_SCOPE_CRIT_BONUS=(\d+)/m)[1])
for (const x of SMALL) {
  const w = weapons.get(x.item)
  if (!w) throw new Error(`no Weapons= line for small item ${x.item}`)
  const n = (k) => Number(w[k] ?? 0)
  const classes = x.mec ? MEC_CLASSES : x.psi ? Object.keys(CLASS_PROPERTY) : Object.entries(CLASS_PROPERTY).filter(([, p]) => equippable(p, w.props.includes('AnyClass') || w.props.length === 0 ? ['AnyClass'] : w.props, x.item)).map(([c]) => c)
  const anyone = !x.mec && classes.length === Object.keys(CLASS_PROPERTY).length
  out.push(
    `+SmallItems=(Item=${x.item}, Template=${smallTemplate(x.item)}, Enum=${ITEMS[x.item]}, Kind=${x.kind}, Look=${x.look}, Damage=${Math.max(0, n('iDamage'))}, Environment=${n('iEnvironmentDamage')}, ` +
      `Radius=${Math.round((n('iRadius') / 96) * 1.5)}, Range=${Math.round(n('iRange') / 1.5)}, Aim=${n('iOffenseBonus')}, Crit=${x.crit ?? n('iCritical')}, HP=${n('iHPBonus')}, Will=${n('iWillBonus')}, ` +
      `Ammo=${x.ammo ?? 1}, Pierce=${x.pierce ?? 0}, CritAgainstReaction=${x.critAgainstReaction ?? 0}, Infinite=${INFINITE.includes(x.item)}` +
      // The Foundry's S.C.O.P.E. project: crit for a carrier of the targeting module, half for the laser sight (item 79), not
      // with a pistol (XGAbility_Targeted.CalcCriticalChance; FOUNDRY_SCOPE_CRIT_BONUS).
      (x.item === 74 || x.item === 79 ? `, ScopeCrit=${Math.trunc(scopeCrit / (x.item === 79 ? 2 : 1))}` : '') +
      (x.weaponCrit ? `, WeaponCrit=${x.weaponCrit}` : '') +
      (x.psi ? ', Psionic=true' : '') + (x.stealth ? ', Stealth=true' : '') + (x.respirator ? ', Respirator=true' : '') +
      // (Defense and mobility while carried: every item's line, as GetBackpackStatBonus adds them; DR only where read.)
      `, Defense=${balanceOf(x.item, 'iDefense')}, Mobility=${balanceOf(x.item, 'iMobility')}` + (x.balance ? `, DR=${itemDR.get(x.item) ?? 0}` : '') +
      (anyone ? '' : `, Classes=(${classes.map((c) => `LWS_${c}`).join(',')})`) +
      ')',
  )
}
// Engineering's pace (XGFacility_Engineering.GetWorkPerHour, XGItemTree.GetItemBuildTime, ScaleCost).
const ini = (k) => Number(core.match(new RegExp(`^${k}=([\\d.]+)`, 'm'))[1])
// The Respirator Implant's longer bleed-out (its text: "The bleed-out timer is extended by 2 turns").
out.push('', '[LongWarX2.X2Effect_LWRespirator]', 'ExtraTurns=2')
// The second-wave options' tactical numbers (features/lw-second-wave.md): Absolutely Critical's flanking crit and the usual.
out.push('', '[LongWarX2.X2Effect_LWSecondWave]', `AbsolutelyCriticalFlankCrit=${ini('SW_FLANK_CRIT')}`, `FlankCrit=${ini('FLANKING_CRIT_BONUS')}`,
  `CinematicAim=${ini('ABDUCTION_REWARD_SCI')}`,
  // Aiming Angles (#19; XGTacticalGameCore.CalcAimingAngleMod, native: its numbers as Long War's ini explains them).
  `AimingAngleThreshold=${ini('SW_AIMING_ANGLE_THRESHOLD')}`, `AimingAngleMin=${ini('SW_AIMING_ANGLE_MINBONUS')}`, `AimingAngleMax=${Number(core.match(/^SW_AIMING_ANGLE_MAXBONUS=(-?[\d.]+)/m)[1])}`)
// Long War's damaged gear and its repair (features/lw-gear-repair.md; LWGearRepair): each item's damage chance after a
// mission (BalanceMods_Classic's iWill, "Max%DamagedChance", read by XGGameData.GetMecBaseArmor), Wear and Tear's chance
// (SW_RARE_PSI), a repair's share of the build time (CB_EXPERT_BONUS), its share of the cost (XGFacility_CyberneticsLab's
// m_fMecRepairCostMod: EW's 0.5, which Long War's ini leaves as it is), its least hours and the Foundry project that speeds it.
out.push('', '[LongWarX2.LWGearRepair]', `WearChance=${ini('SW_RARE_PSI')}`, `TimeShare=${ini('CB_EXPERT_BONUS')}`, 'CostShare=0.5',
  'MinHours=72', 'FasterFoundry=5', 'FasterScale=0.67',
  ...[...core.matchAll(/^BalanceMods_Classic=\(eType=(\d+),.*?iWill=(-?\d+)/gm)].filter((m) => Number(m[2]) > 0).map((m) => `+Chances=(Item=${m[1]}, Chance=${m[2]})`))
// Red Fog's caps (SW_ABDUCTION_SITES and SW_COVER_INCREASE, as Long War's ApplyHPStatPenalties reads them).
out.push('', '[LongWarX2.LWX2SecondWave]', `RedFogAim=${ini('SW_ABDUCTION_SITES')}`, `RedFogMobility=${ini('SW_COVER_INCREASE')}`,
  `SatelliteIncrease=${ini('SW_SATELLITE_INCREASE')}`,
  // Dynamic War (#9; features/lw-dynamic-war.md): its master coefficient and the passes a mission needs.
  `Marathon=${ini('SW_MARATHON')}`, `MarathonPasses=${ini('SW_ELERIUM_LOSS')}`)
// Quick and Dirty (ContBalance_Classic[33]) and Green Fog (ContBalance_Normal[1] and [2]: its toggle's step, its most).
const cont = (arr, k) => core.match(new RegExp(`^${arr}\\[${k}\\]=\\(([^)]*)\\)`, 'm'))[1]
const field = (s, f) => Number(s.match(new RegExp(`${f}=(-?\\d+)`))[1])
const qd = cont('ContBalance_Classic', 33), gfAim = cont('ContBalance_Normal', 1), gfWill = cont('ContBalance_Normal', 2)
out.push(`QuickAndDirtyPct=${field(qd, 'iEngineers1')}`, `QuickAndDirtyMin=${field(qd, 'iScientists1')}`, `QuickAndDirtyMax=${field(qd, 'iEngineers2')}`,
  `GreenFogAimStep=${field(gfAim, 'iScientists1')}`, `GreenFogAimMax=${field(gfAim, 'iEngineers1')}`,
  `GreenFogWillStep=${field(gfWill, 'iScientists1')}`, `GreenFogWillMax=${field(gfWill, 'iEngineers1')}`)
// Flight's air evasion (AIR_EVADE_DEF: the defence a flying unit with eAP_AirEvade has, in place of cover).
out.push('', '[LongWarX2.X2Effect_LWFlying]', `AirEvade=${ini('AIR_EVADE_DEF')}`)
out.push('', '[LongWarX2.LWGearRules]')
out.push(`EngineerRate=${ini('ABDUCTION_REWARD_ENG')}`, `TimeBalance=${ini('ITEM_TIME_BALANCE')}`, `WorkshopBonus=${ini('WORKSHOP_ENG_BONUS')}`)
// The arc thrower: Long War's multiplier on Enemy Within's stun chance (UFO_PSI_LINK_SURVIVE, the name notwithstanding),
// and its range in tiles (APPROXIMATION: Enemy Within's is not in its config).
out.push('[LongWarX2.X2AbilityToHitCalc_LWStun]', `StunBalance=${ini('UFO_PSI_LINK_SURVIVE')}`, '[LongWarX2.X2Ability_LWArcThrower]', 'ArcThrowerRange=4', '[LongWarX2.LWGearRules]')
// What engineering builds: the weapons and armours with a cost; -1 (the starting kit) is never built. And the
// interceptors' weapons and the Firestorm (the hangar, features/lw-hangar.md), the Skeleton Key (lw-story.md).
// And the interceptors' consumables (125 Defense Matrix: Dodge, 126 UFO Tracking: Boost, 127 Uplink Targeting: Aim), after
// their Foundry project (26) and their research (XGInterceptionEngagement.IsConsumableResearched).
const CRAFT = [117, 119, 120, 121, 122, 104, 184, 125, 126, 127]
// XGFacility_Engineering.GetItemProjectCost's own cases: items consumed beyond the item requirement (the
// Firestorm UFO power sources and navigation computers, the Skeleton Key the Outsider Shard).
const SPECIAL = { 104: [[170, 4], [168, 8]], 184: [[183, 1]] }
out.push(
  '; Builds: Cash (\u00a7), Elerium, Alloys, Meld; Days and Engineers: a unit is Days x Engineers x 24 hours of work;',
  '; Tech: the Long War tech id researched first; ItemReq: one consumed per item built; Foundry: the project done first.',
)
// The SHIVs (features/lw-shivs-mecs.md): engineering builds the robot itself, a unit of XCOM's crew (its character template),
// and the SHIVs' weapons (X2Item_LWSHIVWeapons; the Minigun comes with every SHIV and is never built).
const SHIVS = { 100: 'LWSHIV', 101: 'LWSHIV_Alloy', 102: 'LWSHIV_Hover', 109: 'LWSHIV_Minigun', 110: 'LWSHIV_Sentry', 111: 'LWSHIV_Laser', 112: 'LWSHIV_Plasma' }
// The MEC suits and MEC weapons (features/lw-shivs-mecs.md; their templates X2Item_LWMECGear): Armors= with eAP_MEC (not the
// civvies), Weapons= with eWP_Mec and a damage (not the subsystems).
for (const [id, a] of readArmours(core, ITEMS)) if (a.props.includes('MEC') && ITEMS[id] !== 'eItem_MecCivvies') SHIVS[id] = `LWMEC_Suit_${id}`
for (const [id, w] of weapons) if (w.props.includes('Mec') && Number(w.iDamage) > 0 && !/Mec(Flame|Kinetic|Proximity|Electro|Grenade|Restorative)/.test(ITEMS[id] ?? '')) SHIVS[id] = `LWMEC_Weapon_${id}`
SHIVS[ITEMS.indexOf('eItem_MecKineticArm')] = 'LWMEC_KineticStrike'
for (const items of [...Object.values(FAMILIES), Object.keys(ARMOURS).map(Number), CRAFT, SMALL.map((x) => x.item), Object.keys(SHIVS).map(Number)]) {
  for (const item of items) {
    if (item === null) continue
    const b = balance.get(item)
    const t = itemTree.get(item)
    if (!t) throw new Error(`item ${item} is not in data/itemtree.json`)
    if (!b || b.cash < 0 || b.days < 0) continue
    out.push(
      `+Builds=(Item=${item}, Template=${SHIVS[item] ?? itemTemplate(item, ITEMS)}, Cash=${b.cash}, Elerium=${b.elerium}, Alloys=${b.alloys}, Meld=${b.meld}, ` +
        `Days=${b.days}, Engineers=${Math.abs(b.engineers)}, Category=${t.category ?? 0}` +
        (t.tech ? `, Tech=${t.tech.id}` : '') +
        (SPECIAL[item]
          ? `, ItemReq=${itemTemplate(SPECIAL[item][0][0], ITEMS)}, ItemReqCount=${SPECIAL[item][0][1]}` +
            (SPECIAL[item][1] ? `, ItemReq2=${itemTemplate(SPECIAL[item][1][0], ITEMS)}, ItemReq2Count=${SPECIAL[item][1][1]}` : '')
          : t.item
            ? `, ItemReq=${SHIVS[t.item.id] ?? itemTemplate(t.item.id, ITEMS)}`
            : '') +
        (t.foundry ? `, Foundry=${t.foundry}` : '') +
        ')',
    )
  }
}

// The Foundry's projects (FoundryBalance; what each needs first, from the Tree's data/techtree.json): iFragments
// packs fragments (low) and meld (high: / 1000); the item in stores is also consumed, Items of it.
const foundryRules = new Map(treeData('techtree.json').foundry.map((f) => [f.id, f]))
const FOUNDRY = treeData('enums.json').enums.EFoundryTech
out.push(
  '; Foundry: Days and Engineers as for Builds; Cash, Elerium, Alloys, Fragments, Meld; Tech: researched first;',
  '; Item: in stores and consumed, Items of it; EverHad: an item that must have been held; Credits: the research credits that cut its time.',
)
for (const m of core.matchAll(/^FoundryBalance=\((.*?)\)/gm)) {
  const f = Object.fromEntries(m[1].split(',').filter((p) => p.includes('=')).map((p) => p.split('=').map((x) => x.trim())))
  const id = /^\d+$/.test(f.eTech) ? Number(f.eTech) : FOUNDRY.indexOf(f.eTech)
  const rule = foundryRules.get(id)
  if (!rule) throw new Error(`Foundry project ${f.eTech} is not in data/techtree.json`)
  const n = (k) => Number(f[k])
  out.push(
    `+Foundry=(Id=${id}, Enum=${rule.enum ?? 'none'}, Days=${n('iTime')}, Engineers=${n('iEngineers')}, Cash=${n('iCash')}, Elerium=${n('iElerium')}, Alloys=${n('iAlloys')}, ` +
      `Fragments=${n('iFragments') % 1000}, Meld=${Math.trunc(n('iFragments') / 1000)}, Tech=${rule.requires}` +
      (rule.in_stores ? `, Item=${itemTemplate(rule.in_stores.id, ITEMS)}, Items=${n('iNumItems')}` : '') +
      (rule.ever_had ? `, EverHad=${itemTemplate(rule.ever_had.id, ITEMS)}` : '') +
      (rule.credits?.length ? `, Credits=(${rule.credits.join(',')})` : '') +
      ')',
  )
}
// The perks items give while carried (XGStorage.ClaimItem: the item's iStructureReq, ItemBalance_Normal's iAlloys / 1000,
// held while the item is equipped; LWGearRules.CarriedPerks).
out.push('; CarriedPerks: the Long War perk an item gives its carrier (X2DownloadableContentInfo_LongWarX2, as the alien perks map them).')
for (const [item, b] of [...balance].sort((x, y) => x[0] - y[0])) {
  if (item <= 0 || !b.perk || !ITEMS[item]) continue
  out.push(`+CarriedPerks=(Template=${SHIVS[item] ?? itemTemplate(item, ITEMS)}, Perk=${b.perk})`)
}
// The grey market (XGItemTree.GetItemSalePrice, CanBeSold; LWGreyMarket): what Long War buys and for how much, its
// ItemBalance_Normal's iCash (an item engineering builds, iTime not -1: 40% of it); never craft, their weapons, the satellite
// or the Skyranger (CanBeSold's list). Corpse: Xenological Remedies raises its price (XGFacility_Engineering.IsCorpseItem).
const UNSELLABLE = new Set([66, 100, 101, 102, 103, 104, 105, 116, 117, 118, 119, 120, 121, 122, 125, 126, 127, 184, 106, 192])
const isCorpse = (i) => i === 187 || i === 188 || (i >= 134 && i <= 144) || (i >= 146 && i <= 147)
out.push(
  '',
  "; The grey market (LWGreyMarket): Long War's price for each item it buys (built items at 40%), Corpse for Xenological Remedies.",
  '[LongWarX2.LWGreyMarket]',
  ...[...balance]
    .filter(([item, b]) => item > 0 && b.cash > 0 && !UNSELLABLE.has(item) && ITEMS[item] && !/^eItem_(BEGIN|END)_/.test(ITEMS[item]))
    .sort((a, b) => a[0] - b[0])
    // Alloys and elerium are XCOM 2's own resources in the port (X2Item_LWArtifacts.ItemFor).
    .map(([item, b]) => `+Sales=(Item=${item}, Template=${{ 161: 'EleriumDust', 162: 'AlienAlloy' }[item] ?? SHIVS[item] ?? itemTemplate(item, ITEMS)}, Cash=${b.days !== -1 ? Math.trunc(b.cash * 0.4) : b.cash}${isCorpse(item) ? ', Corpse=true' : ''})`),
)
// The MEC flamethrower's cone (X2Ability_LWMECFlamethrower): EW's sweep, as Long War configures it.
const flame = (k) => Number(core.match(new RegExp(`\\[XComGame\\.XGAction_FireCustom_Flamethrower\\][^\\[]*?^${k}=([\\d.]+)`, 'm'))?.[1] ?? 0)
out.push('', "; The MEC flamethrower's cone: Long War's XGAction_FireCustom_Flamethrower Range (tiles) and SweepAngle (degrees).",
  '[LongWarX2.X2Ability_LWMECFlamethrower]', `RangeTiles=${flame('Range')}`, `SweepAngle=${flame('SweepAngle')}`)
console.log(out.join('\r\n'))
