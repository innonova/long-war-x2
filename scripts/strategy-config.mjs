// Long War's strategic numbers as the mod's config (features/lw-geoscape.md):
// LongWarX2/Config/XComLWStrategy.ini, from the player's Long War DefaultGameCore.ini. Long War
// keeps a value per difficulty either as four lines of one key (Normal, Classic, Brutal,
// Impossible) or as keys ending _EASY, _NORMAL, _HARD, _CLASSIC (the same four, its comments say);
// both become a four-entry array here, indexed by XCOM 2's difficulty (Rookie … Legend).
//
// With Long War's XComStrategyGame.upk as well, the aliens' monthly plan (XGStrategyAI.AIAddNewObjectives,
// read with upkit) is written too: by the aliens' resource tier and aggression, the abductions,
// terror missions and UFOs of each objective they send that month; and the countries the aliens
// turn to once a country has left the council (DetermineBestTerrorTarget).
//
//   node scripts/strategy-config.mjs <Long War's DefaultGameCore.ini> [<XComStrategyGame.upk>] > LongWarX2/Config/XComLWStrategy.ini
import { readFileSync } from 'node:fs'
import { execFileSync } from 'node:child_process'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const core = readFileSync(process.argv[2], 'latin1')
const strategyUpk = process.argv[3]
const lines = core.split(/\r?\n/)
/** Every value of a key, in file order (comments stripped). */
const values = (key) =>
  lines
    .map((l) => new RegExp(`^${key}\\s*=\\s*([^;\\s]+)`, 'i').exec(l))
    .filter(Boolean)
    .map((m) => Number(m[1].replace(/f$/, '')))
const one = (key) => {
  const v = values(key)
  if (!v.length) throw new Error(`${key} not in the ini`)
  return v[0]
}
/** Four values by difficulty: four lines of the key, or _EASY/_NORMAL/_HARD/_CLASSIC. */
const four = (key) => {
  const v = values(key)
  if (v.length >= 4) return v.slice(0, 4)
  const named = ['EASY', 'NORMAL', 'HARD', 'CLASSIC'].map((d) => values(`${key}_${d}`)[0])
  if (named.every((x) => x !== undefined)) return named
  if (v.length === 1) return [v[0], v[0], v[0], v[0]]
  throw new Error(`${key}: no value per difficulty`)
}

// The council countries: Long War's funding table, in ECountry order; "fc" marks the council.
const COUNTRY = ['USA', 'Russia', 'China', 'UK', 'Germany', 'France', 'Japan', 'India', 'Australia', 'Italy', 'SouthKorea', 'Turkey', 'Indonesia', 'Spain', 'Pakistan', 'Canada', 'Iran', 'Israel', 'Egypt', 'Brazil', 'Argentina', 'Mexico', 'SouthAfrica', 'Poland', 'Ukraine', 'Nigeria', 'Venezuela']
const NAME = { USA: 'United States', UK: 'United Kingdom', SouthAfrica: 'South Africa' }
const CONTINENT = { USA: 0, Canada: 0, Mexico: 0, Brazil: 1, Argentina: 1, UK: 2, France: 2, Germany: 2, Russia: 2, China: 3, Japan: 3, India: 3, Australia: 3, Egypt: 4, Nigeria: 4, SouthAfrica: 4 }
// Two tables of the same key, one country a line each: the monthly funding, then the starting cash
// by home country, each after its own FundingBalance lines (the multiplier, by difficulty).
const funding = lines.map((l) => /^FundingAmounts\s*=\s*(\d+)\s*;\s*(\d+)(f?c?)/.exec(l)).filter(Boolean)
const half = funding.length / 2
const council = funding
  .slice(0, half)
  .filter((m) => m[3] === 'fc')
  .map((m) => ({ id: COUNTRY[Number(m[2])], funding: Number(m[1]), cash: Number(funding[half + funding.slice(0, half).indexOf(m)][1]) }))
if (council.length !== 16) throw new Error(`${council.length} council countries, expected 16`)
// The satellite: its price and build time (days) from the item balance.
const sat = /^Itembalance_Normal=\(eItem=eItem_Satellite,\s*iCash=(\d+),.*?iTime=(\d+)/im.exec(core)

const neighbours = strategyUpk ? terrorNeighbours(strategyUpk) : {}

const q = (s) => `"${s}"`
const arr = (key, v) => v.map((x, i) => `${key}[${i}]=${x}`)
