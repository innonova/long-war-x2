/**
 * The monthly plan from Long War's own code: the non-Marathon branch of AIAddNewObjectives, a block
 * per resource tier (iNumUFOs, the aliens' resources / 50) holding a block per aggression
 * (iMonth, 0 to 4). In each: the abductions (one number, or a 50/50 between two), the terror
 * missions, and an AddUFOs(objective) per UFO, some under a 50% roll; UFOs before the aggression
 * blocks come in every aggression of that tier.
 */
function decompile(upk, fn) {
  const upkit = process.env.UPKIT ?? join(dirname(fileURLToPath(import.meta.url)), '..', 'node_modules', '@innonova', 'upkit', 'dist', 'upkit.mjs')
  return execFileSync(process.execPath, [upkit, 'decompile', upk, fn], { encoding: 'utf8', maxBuffer: 64 << 20 })
    .split(/\r?\n/)
    .map((l) => l.replace(/__asm\(ByteConst, (\d+)\)/g, '$1').replace(/0x0*(\d+)/g, '$1').trim())
    .filter((l) => l && l !== ';')
}

/**
 * The countries the aliens turn to once a country has left (XGStrategyAI.DetermineBestTerrorTarget):
 * a switch on the country that left, each case adding its neighbours still in the council. Long War
 * wrote the neighbours' country numbers where the code expects an alien (IsAssetPresent(eChar_…)),
 * so the names are ECharacter's and the numbers ECountry's.
 */
function terrorNeighbours(upk) {
  const CHAR = ['None', 'Civilian', 'Soldier', 'Tank', 'Sectoid', 'Floater', 'Thinman', 'Muton', 'Cyberdisc', 'SectoidCommander', 'FloaterHeavy', 'MutonElite', 'Ethereal', 'Chryssalid', 'Zombie', 'MutonBerserker', 'Sectopod', 'Drone', 'Outsider', 'EtherealUber', 'BattleScanner', 'Mechtoid', 'Mechtoid_Alt', 'Seeker', 'ExaltOperative', 'ExaltSniper']
  const result = {}
  let left
  for (const l of decompile(upk, 'XGStrategyAI.DetermineBestTerrorTarget')) {
    let m
    if ((m = /^__asm\(Case, \d+, (\d+)\);$/.exec(l))) left = COUNTRY[Number(m[1])]
    else if (/^__asm\(Case, \d+\);$/.test(l)) left = undefined
    else if ((m = /^IsAssetPresent\(eChar_(\w+), arrAll\);$/.exec(l)) && left) {
      const n = CHAR.indexOf(m[1])
      if (n < 0 || !COUNTRY[n]) throw new Error(`DetermineBestTerrorTarget: ${m[1]} is no country`)
      ;(result[left] ??= []).push(COUNTRY[n])
    }
  }
  if (Object.keys(result).length !== 16) throw new Error(`DetermineBestTerrorTarget: ${Object.keys(result).length} countries read, expected 16`)
  return result
}

function monthlyPlan(upk) {
  const src = decompile(upk, 'XGStrategyAI.AIAddNewObjectives')
  const start = src.findIndex((l) => l.startsWith('if (!IsOptionEnabled(eGO_Marathon))'))
  const cells = new Map()
  let depth = 0
  let tier = -1
  let phase = -1
  let tierDepth = 0
  let phaseDepth = 0
  let roll = false
  let rollDepth = 0
  const shared = new Map()
  for (const l of src.slice(start + 1)) {
    if (l === '{') {
      depth++
      continue
    }
    if (l === '}') {
      depth--
      if (roll && depth < rollDepth) roll = false
      if (phase >= 0 && depth < phaseDepth) phase = -1
      if (tier >= 0 && depth < tierDepth) tier = -1
      if (depth <= 0) break
      continue
    }
    let m
    if ((m = /^if \(iNumUFOs == (\d+)\)$/.exec(l))) {
      tier = Number(m[1])
      tierDepth = depth + 1
      shared.set(tier, [])
      continue
    }
    if ((m = /^if \(iMonth == (\d+)\)$/.exec(l)) && tier >= 0) {
      phase = Number(m[1])
      phaseDepth = depth + 1
      cells.set(`${tier}:${phase}`, { abductions: [0, 0], terror: 0, ufos: [...shared.get(tier)], maybe: [] })
      continue
    }
    if (/^if \(Rand\(2\) == 0\)$/.test(l)) {
      roll = true
      rollDepth = depth + 1
      continue
    }
    const cell = tier >= 0 && phase >= 0 ? cells.get(`${tier}:${phase}`) : undefined
    if ((m = /^AddUFOs\((\d+), arrVisibleTargets\);$/.exec(l))) {
      if (cell) (roll ? cell.maybe : cell.ufos).push(Number(m[1]))
      else if (tier >= 0) shared.get(tier).push(Number(m[1]))
      continue
    }
    if (!cell) continue
    if ((m = /^iNumAbductions = Rand\(2\) == 0 \? (\d+) : (\d+);$/.exec(l))) cell.abductions = [Number(m[1]), Number(m[2])]
    else if ((m = /^iNumAbductions = (\d+);$/.exec(l))) cell.abductions = [Number(m[1]), Number(m[1])]
    else if ((m = /^iNumTerror = (\d+);$/.exec(l))) cell.terror = Number(m[1])
  }
  if (cells.size !== 25) throw new Error(`the monthly plan: ${cells.size} cells read, expected 25`)
  return [
    "; The aliens' monthly plan (Long War's XGStrategyAI.AIAddNewObjectives): by resource tier (resources / 50)",
    '; and aggression (0 to 4): abductions (a 50/50 between two numbers), terror missions, UFOs by objective',
    '; (0 recon, 1 scout, 2 harvest, 4 hunt, 7 and 8 infiltration) and those under a 50% roll.',
    ...[...cells].map(
      ([k, c]) => `+Plan=(Tier=${k.split(':')[0]}, Aggression=${k.split(':')[1]}, Abductions=${c.abductions[0]}, AbductionsAlt=${c.abductions[1]}, Terror=${c.terror}, Ufos=(${c.ufos.join(',')}), MaybeUfos=(${c.maybe.join(',')}))`,
    ),
  ]
}
