// Enemy Within's maps for Long War's missions (features/lw-missions.md, EW maps as the missions' ground):
// LongWarX2/Config/XComLWEWMaps.ini, from Long War's DefaultMaps.ini (its Maps= lines): each map in rotation
// for an abduction, a crash site, a landed UFO or a terror site, with the ship its crash and landed maps are for
// (the port's ship ids, which are Long War's: 4 Scout … 9 Overseer as EW's EShipType, and Long War's own 10 Fighter,
// 11 Raider, 12 Harvester, 13 Terror Ship, 14 Assault Carrier, which its list gives as numbers, the same maps again)
// and whether it is a night map. Names only. The mod plays a mission on one of these that the player's machine has
// converted (tools/convert/ew-maps.ts). Also the shared settings of the converted maps (lights, materials).
//   node scripts/maps-config.mjs <Long War's DefaultMaps.ini> > LongWarX2/Config/XComLWEWMaps.ini
import { readFileSync } from 'node:fs'

const text = readFileSync(process.argv[2], 'latin1')
const SHIPS = { eShip_None: 0, eShip_UFOSmallScout: 4, eShip_UFOLargeScout: 5, eShip_UFOAbductor: 6, eShip_UFOSupply: 7, eShip_UFOBattle: 8, eShip_UFOEthereal: 9 }
const KINDS = { eMission_Abduction: 'Abduction', eMission_Crash: 'Crash', eMission_LandedUFO: 'Landed', eMission_TerrorSite: 'Terror' }
const maps = []
for (const line of text.split(/\r?\n/)) {
  const m = line.match(/^\+?Maps=\(\s*MapFamily="([^"]*)",\s*Name="([^"]*)".*?MissionType=(\w+),\s*bInRotation=(\w+),\s*TimeOfDay=(\w+),\s*ShipType=(\w+)/)
  if (!m) continue
  const [, family, name, type, rotation, time, ship] = m
  if (!KINDS[type] || rotation !== 'True') continue
  const shipId = /^\d+$/.test(ship) ? Number(ship) : SHIPS[ship]
  if (shipId === undefined) throw new Error(`${name}: unknown ship ${ship}`)
  maps.push(`+Maps=(Name="${name}", Family="${family}", Kind=${KINDS[type]}, Ship=${shipId}, Night=${time === 'eMissionTime_Night'})`)
}
const count = (k) => maps.filter((l) => l.includes(`Kind=${k},`)).length
console.log(
  [
    "; Enemy Within's maps for Long War's missions, generated by scripts/maps-config.mjs from Long War's",
    `; DefaultMaps.ini: ${count('Abduction')} abduction, ${count('Crash')} crash site, ${count('Landed')} landed UFO and ${count('Terror')} terror maps. Do not edit by hand.`,
    '[LongWarX2.LWX2EWMapPieces]',
    "; The converted map a quick launch places (no campaign to choose one).",
    'DefaultMap="CSmallScout_Badlands"',
    '; For development: this converted map for every Long War mission, whatever its kind ("": Long War\'s list decides).',
    'ForceMap=""',
    "; EW's lights (point, spot, its sun and sky), spawned as movable lights: the kinds placed and a scale on their",
    "; brightness (3: EW's lightmaps carried bounced light too; judged by eye on CSmallScout_Badlands).",
    'LightScale=3',
    '+LightKinds=Point',
    '+LightKinds=Spot',
    '+LightKinds=Sun',
    '+LightKinds=Sky',
    "; XCOM 2 cannot draw EW's materials: each is replaced by an instance of one of these parents",
    "; (by the kind of the EW material) given the EW textures. Empty: the EW materials are kept.",
    'PropParent="Materials.Approved.Props_SD"',
    'FoliageParent="Materials.Approved.Vegetations_VO"',
    'AlienParent="Materials.Approved.Alien_Props"',
    "; Scalars set on every stand-in. The parents' placeholder mask (no EW texture fills it) made the surfaces glossy",
    '; and grey; no specular reads cleanly (features/lw-missions.md, compared on URB_HighwayFallen).',
    '+StandinScalars=(Name=SpecularScale, Value=0)',
    "; and textures: the parents' mask (XCOM 2's packed light channels) white, which is their own value when a material",
    '; has no mask (their NoMasksMap switch puts 1 in every channel); the placeholder in its place darkened every surface.',
    '+StandinTextures=(Name=Masks, Path="EngineResources.WhiteSquareTexture")',
    ...maps,
  ].join('\r\n'),
)
