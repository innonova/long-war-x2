//   node scripts/maps-config.mjs <Long War's DefaultMaps.ini> > LongWarX2/Config/XComLWEWMaps.ini
import { readFileSync } from 'node:fs'
/** The fixed rooms' animation levels, with EW's people in them (features/ew-base-people.md). */
const PEOPLE_LEVELS = ['Anim_ScienceLabs', 'Anim_Engineering', 'Anim_Barracks', 'Anim_Hangar', 'Anim_MissionControl', 'Anim_Armory']

const text = readFileSync(process.argv[2], 'latin1')
const SHIPS = { eShip_None: 0, eShip_UFOSmallScout: 4, eShip_UFOLargeScout: 5, eShip_UFOAbductor: 6, eShip_UFOSupply: 7, eShip_UFOBattle: 8, eShip_UFOEthereal: 9 }
const KINDS = { eMission_Abduction: 'Abduction', eMission_Crash: 'Crash', eMission_LandedUFO: 'Landed', eMission_TerrorSite: 'Terror',
  // EXALT's covert missions (features/lw-exalt.md): played with their variant level, the streamed map that carries them.
  eMission_CovertOpsExtraction: 'CovertExtraction', eMission_CaptureAndHold: 'DataRecovery',
  // The story's missions (features/lw-story.md): the alien bases, the Temple Ship, the HQ assault, EXALT's base.
  eMission_AlienBase: 'AlienBase', eMission_Final: 'Final', eMission_HQAssault: 'HQAssault', eMission_ExaltRaid: 'ExaltRaid' }
const maps = []
for (const line of text.split(/\r?\n/)) {
  // (Names quoted or not: the covert extractions' are bare.)
  const m = line.match(/^\+?Maps=\(\s*MapFamily="?([^",]*)"?,\s*Name="?([^",]*?)"?,.*?MissionType=(\w+),\s*bInRotation=(\w+),\s*TimeOfDay=(\w+),\s*ShipType=(\w+)/)
  if (!m) continue
  const [, family, name, type, rotation, time, ship] = m
  if (!KINDS[type] || rotation !== 'True') continue
  const shipId = /^\d+$/.test(ship) ? Number(ship) : SHIPS[ship]
  if (shipId === undefined) throw new Error(`${name}: unknown ship ${ship}`)
  const level = /^(Covert|Data)/.test(KINDS[type]) ? [...line.matchAll(/MapName="?(\w+)/g)].map((x) => x[1]).find((x) => !/^(CIN_|patch)/i.test(x)) : undefined
  maps.push(`+Maps=(Name="${name}", Family="${family}", Kind=${KINDS[type]}, Ship=${shipId}, Night=${time === 'eMissionTime_Night'}${level ? `, Level="${level}"` : ''})`)
}
