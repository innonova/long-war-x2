// Long War's aliens' stats (features/lw-aliens.md): LongWarX2/Config/XComLWAliens.ini, from stock Long War's
// DefaultGameCore.ini (XGTacticalGameCore): each species' base stats (Characters=), the difficulty's adjustments
// (BalanceMods_Easy: iCritHit is the difficulty, 0-3) and the automatic upgrades the aliens' research brings
// (BalanceMods_Normal: iCritHit is the research level from which it applies; aim, defense, HP and will packed as xxyy).
// Numbers only, by species (EW's ECharacter).
//   node scripts/aliens-config.mjs <Long War's DefaultGameCore.ini> > LongWarX2/Config/XComLWAliens.ini
import { readFileSync } from 'node:fs'

const ECHARACTER = ['None', 'Civilian', 'Soldier', 'Tank', 'Sectoid', 'Floater', 'Thinman', 'Muton', 'Cyberdisc', 'SectoidCommander',
  'FloaterHeavy', 'MutonElite', 'Ethereal', 'Chryssalid', 'Zombie', 'MutonBerserker', 'Sectopod', 'Drone', 'Outsider', 'EtherealUber',
  'BattleScanner', 'Mechtoid', 'Mechtoid_Alt', 'Seeker', 'ExaltOperative', 'ExaltSniper', 'ExaltHeavy', 'ExaltMedic',
  'ExaltEliteOperative', 'ExaltEliteSniper', 'ExaltEliteHeavy', 'ExaltEliteMedic']
const species = (name) => ECHARACTER.indexOf(name.replace(/^eChar_/, ''))
const text = readFileSync(process.argv[2], 'latin1')
const field = (line, k) => Number(new RegExp(`\\b${k}=\\s*(-?\\d+)`).exec(line)?.[1] ?? 0)

const out = [
  "; Long War's aliens' stats, generated by scripts/aliens-config.mjs from stock Long War's DefaultGameCore.ini",
  '; (features/lw-aliens.md). Do not edit by hand. Species are EW\'s ECharacter numbers (4 Sectoid, 5 Floater …).',
  '[LongWarX2.LWAlienStats]',
]
for (const m of text.matchAll(/^Characters=\(.*?iType=(eChar_\w+),(.*)$/gm)) {
  const s = species(m[1])
  if (s < 4 || s > 23) continue
  const l = m[2]
  out.push(`+Base=(Species=${s}, HP=${field(l, 'HP')}, Aim=${field(l, 'Offense')}, Defense=${field(l, 'Defense')}, Mobility=${field(l, 'Mobility')}, Sight=${field(l, 'SightRadius')}, Will=${field(l, 'Will')}, Crit=${field(l, 'CritHitChance')})`)
}
out.push("; The difficulty's adjustments (0 Normal, 1 Classic, 2 Brutal, 3 Impossible: Long War's names for XCOM 2's four).")
for (const m of text.matchAll(/^BalanceMods_Easy=\(\s*eType=(eChar_\w+),(.*)\)/gm)) {
  const s = species(m[1])
  if (s < 4 || s > 23) continue
  const l = m[2]
  const v = { Damage: field(l, 'iDamage'), Aim: field(l, 'iAim'), Defense: field(l, 'iDefense'), HP: field(l, 'iHP'), Mobility: field(l, 'iMobility'), Will: field(l, 'iWill') }
  if (Object.values(v).every((x) => x === 0)) continue
  out.push(`+Difficulty=(Species=${s}, Level=${field(l, 'iCritHit')}, ${Object.entries(v).map(([k, x]) => `${k}=${x}`).join(', ')})`)
}
out.push("; The automatic upgrades from the aliens' research level (Research: from which level; xxyy fields unpacked).")
for (const m of text.matchAll(/^BalanceMods_Normal=\(\s*eType=(eChar_\w+),(.*)\)/gm)) {
  const s = species(m[1])
  if (s < 4 || s > 23) continue
  const l = m[2]
  const aim = field(l, 'iAim'), def = field(l, 'iDefense'), hp = field(l, 'iHP'), will = field(l, 'iWill')
  out.push(`+Upgrade=(Species=${s}, Research=${field(l, 'iCritHit')}, Damage=${field(l, 'iDamage')}, Aim=${aim % 100}, Crit=${Math.trunc(aim / 100)}, ` +
    `Defense=${def % 100}, DR=${Math.trunc(def / 100) / 10}, HP=${hp % 100}, Shield=${Math.trunc(hp / 100)}, Mobility=${field(l, 'iMobility')}, Will=${will % 100}, Regen=${Math.trunc(will / 100)})`)
}
// Pod leaders and navigators (BalanceMods_Hard, uncommented lines): from a research level (iCritHit's high digits) a leader
// of at least a level (its low digits under 10) or a navigator at a chance in 100 (10 or more), its stat upgrades, a perk
// (iMobility: EW's EPerkType) and the pawn's scale in percent (iDefense).
out.push("; Pod leaders (Level: the leader's level from which it applies) and navigators (Chance in 100, any member), from a research level.")
for (const m of text.matchAll(/^BalanceMods_Hard=\(\s*eType=(eChar_\w+),(.*)\)/gm)) {
  const s = species(m[1])
  if (s < 4 || s > 23) continue
  const l = m[2]
  const code = field(l, 'iCritHit')
  const low = code % 100
  out.push(`+Leader=(Species=${s}, Research=${Math.trunc(code / 100)}, ${low < 10 ? `Level=${low}, Chance=0` : `Level=0, Chance=${low}`}, ` +
    `HP=${field(l, 'iHP')}, Aim=${field(l, 'iAim')}, Damage=${field(l, 'iDamage')}, Will=${field(l, 'iWill')}, Perk=${field(l, 'iMobility')}, Scale=${field(l, 'iDefense')})`)
}
// Each species' weapon (EW's: the item its unit carries) and Long War's damage for it; the alien's shots with its XCOM 2
// weapon are shifted from that weapon's base damage to this (X2Effect_LWAlienDamage).
const WEAPONS = {
  Sectoid: 'SectoidPlasmaPistol', SectoidCommander: 'PlasmaPistol', Floater: 'PlasmaLightRifle_Floater', FloaterHeavy: 'HeavyPlasma_Floater',
  Thinman: 'PlasmaLightRifle_ThinMan', Muton: 'PlasmaAssaultRifle_Muton', MutonElite: 'HeavyPlasma_Muton', MutonBerserker: 'MutonBlade',
  Cyberdisc: 'CyberdiscWeapon', Drone: 'DroneBeam', Outsider: 'OutsiderWeapon', Seeker: 'SeekerPlasmaPistol', Mechtoid: 'MechtoidPlasmaCannon',
  Chryssalid: 'ChryssalidClaw', Zombie: 'ZombieFist', Sectopod: 'SectopodChestCannon', Ethereal: 'PlasmaLightRifle', EtherealUber: 'PlasmaLightRifle',
}
out.push("; Each species' weapon's damage (Long War's Weapons= line for the item EW's unit carries).")
for (const [name, item] of Object.entries(WEAPONS)) {
  const line = new RegExp(`^Weapons=\\(\\s*strName="",\\s*iType=eItem_${item},.*$`, 'm').exec(text)?.[0]
  if (!line) throw new Error(`no Weapons= line for eItem_${item}`)
  out.push(`+Weapon=(Species=${species(name)}, Damage=${field(line, 'iDamage')})`)
}
console.log(out.join('\r\n'))
