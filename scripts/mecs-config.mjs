// Long War's MEC troopers as the mod's config (features/lw-shivs-mecs.md): LongWarX2/Config/XComLWMECs.ini, from the player's
// Long War DefaultGameCore.ini (the MEC suits, Armors= with eAP_MEC; the MEC weapons, Weapons= with eWP_Mec and a damage;
// their engineering costs, ItemBalance_Normal; the soldier's base stats, Characters= eChar_Soldier) and DefaultGameData.ini
// (the Cybernetics Lab's price and days), the Tree's data/itemtree.json (what each needs researched first). Numbers only.
//
//   node scripts/mecs-config.mjs <Long War's DefaultGameCore.ini> <Long War's DefaultGameData.ini> > LongWarX2/Config/XComLWMECs.ini
import { readFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { readArmours, readBalance, readWeapons } from './lw-gear.mjs'

const core = readFileSync(process.argv[2], 'latin1')
const data = readFileSync(process.argv[3], 'latin1')
const tree = (f) => JSON.parse(readFileSync(join(dirname(fileURLToPath(import.meta.url)), '..', '..', 'xcom-ew-lw-tree', 'data', f), 'utf8'))
const ITEMS = tree('enums.json').enums.EItemType
const itemTree = new Map(tree('itemtree.json').items.map((i) => [i.id, i]))
const balance = readBalance(core, ITEMS)
const lab = (k) => Number(data.match(new RegExp(`^${k}\\s*=\\s*(-?[\\d.]+)`, 'm'))[1])
const soldier = /^Characters=\(\s*strName="",\s*iType=eChar_Soldier,\s*HP=(\d+),\s*Offense=(\d+),\s*Defense=(-?\d+),\s*Mobility=(\d+),.*?Will=(\d+)/m.exec(core)
if (!soldier) throw new Error('no soldier Characters= line')

const build = (item) => {
  const b = balance.get(item)
  const t = itemTree.get(item)
  if (!b || b.cash < 0 || b.days < 0) return ', Built=false'
  return `, Built=true, Cash=${b.cash}, Elerium=${b.elerium}, Alloys=${b.alloys}, Meld=${b.meld}, Days=${b.days}, Engineers=${Math.abs(b.engineers)}` +
    (t?.tech ? `, Tech=${t.tech.id}` : '') + (t?.item ? `, ItemReq=${t.item.id}` : '')
}
const out = [
  "; Long War 1.0's MEC troopers, generated by scripts/mecs-config.mjs from Long War's DefaultGameCore.ini and DefaultGameData.ini.",
  '; Do not edit by hand.',
  '[LongWarX2.LWMECs]',
  '; The Cybernetics Lab (XGFacility_CyberneticsLab): an augmentation\'s cash, meld and days.',
  `AugmentCash=${lab('m_iModCashCost')}`,
  `AugmentMeld=${lab('m_iModMeldCost')}`,
  `AugmentDays=${lab('m_iModDays')}`,
  "; A MEC's base stats (SetSoldierClass: the soldier's character, eChar_Soldier, and +4 HP), before its rank's gains.",
  `Base=(HP=${Number(soldier[1]) + 4}, Aim=${soldier[2]}, Defense=${soldier[3]}, Mobility=${soldier[4]}, Will=${soldier[5]})`,
  '; Suits (Armors= with eAP_MEC): HP, Defense, Mobility, Will; LargeItems, SmallItems: its subsystem and item slots; Built: whether',
  '; engineering builds it, and its costs (Cash, Elerium, Alloys, Meld, Days, Engineers; Tech, ItemReq: what it needs first).',
]
for (const [id, a] of readArmours(core, ITEMS)) {
  if (!a.props.includes('MEC') || id === ITEMS.indexOf('eItem_MecCivvies')) continue
  out.push(`+Suits=(Item=${id}, HP=${a.iHPBonus}, Defense=${a.iDefenseBonus}, Mobility=${a.iMobilityBonus}, Will=${a.iWillBonus}, LargeItems=${a.iLargeItems}, SmallItems=${a.iSmallItems}${build(id)})`)
}
out.push("; Weapons (Weapons= with eWP_Mec and a damage): Damage, Crit, Aim, Environment, Ammo (iSuppression's last two digits).")
for (const [id, w] of readWeapons(core, ITEMS)) {
  if (!w.props.includes('Mec') || !(Number(w.iDamage) > 0) || /MEC_|Mec(Flame|Kinetic|Proximity|Electro|Grenade|Restorative)/i.test(ITEMS[id] ?? '')) continue
  out.push(`+Weapons=(Item=${id}, Damage=${w.iDamage}, Crit=${w.iCritical}, Aim=${w.iOffenseBonus}, Environment=${w.iEnvironmentDamage}, Ammo=${Number(w.iSuppression) % 100}${build(id)})`)
}
// The Kinetic Strike Module (Weapons= eItem_MecKineticArm): its damage; a melee strike (X2Item_LWMECGear).
const kinetic = ITEMS.indexOf('eItem_MecKineticArm')
const k = readWeapons(core, ITEMS).get(kinetic)
out.push("; The Kinetic Strike Module: a melee strike's Damage.", `KineticStrike=(Item=${kinetic}, Damage=${k.iDamage}, Environment=${Math.max(0, Number(k.iEnvironmentDamage))}${build(kinetic)})`)
console.log(out.join('\r\n'))
