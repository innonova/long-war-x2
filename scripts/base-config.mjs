// Long War's base as the mod's config (features/lw-base.md): LongWarX2/Config/XComLWBase.ini, from the
// player's Long War DefaultGameCore.ini (FacilityBalance and the base's constants) and the Tree's
// data/itemtree.json (each facility's size and the tech it needs, read from XGItemTree.BuildFacilities).
// Numbers only: the facilities' names are Long War's words, written on the player's machine (lw-words.mjs).
//
//   node scripts/base-config.mjs <Long War's DefaultGameCore.ini> > LongWarX2/Config/XComLWBase.ini
import { readFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { itemTemplate } from './lw-gear.mjs'

const core = readFileSync(process.argv[2], 'latin1')
const treeData = (f) => JSON.parse(readFileSync(join(dirname(fileURLToPath(import.meta.url)), '..', '..', 'xcom-ew-lw-tree', 'data', f), 'utf8'))
const enums = treeData('enums.json').enums
const FACILITIES = enums.EFacilityType
const ITEMS = enums.EItemType
const tree = new Map(treeData('itemtree.json').facilities.map((f) => [f.id, f]))

/** A key's value (the first line of it), or each line's value for keys Long War gives per difficulty. */
const one = (k) => Number(core.match(new RegExp(`^${k}\\s*=\\s*(-?[\\d.]+)`, 'm'))[1])
const all = (k) => [...core.matchAll(new RegExp(`^${k}\\s*=\\s*(-?[\\d.]+)`, 'gm'))].map((m) => Number(m[1]))

// XGItemTree.CanHaveMultiple: the facilities a base has one of.
const SINGLE = [17, 18, 19, 20, 11, 12, 13, 23, 22]
// XGFacility_Engineering.GetFacilityProjectCost: items a facility consumes (the Elerium Generator two UFO
// power sources, the Satellite Nexus two UFO navigation computers).
const ITEM_COST = { 16: [170, 2], 14: [168, 2] }

const out = [
  "; Long War 1.0's base, generated by scripts/base-config.mjs from Long War's DefaultGameCore.ini (FacilityBalance",
  "; and the base's constants) and the Tree's data/itemtree.json. Do not edit by hand. Facilities: Long War's",
  '; numbers (Id: EFacilityType); Days to build; Power: made (+) or used (-); Upkeep a month; Tech: the Long War',
  '; tech id researched first; Item: consumed, Items of it; Multiple: a base may have more than one.',
  '[LongWarX2.LWBaseRules]',
]
for (const m of core.matchAll(/^FacilityBalance=\(\s*(.*?)\)/gm)) {
  const f = Object.fromEntries(m[1].split(',').filter((p) => p.includes('=')).map((p) => p.split('=').map((x) => x.trim())))
  const id = FACILITIES.indexOf(f.eFacility)
  const t = tree.get(id)
  if (!t) throw new Error(`facility ${f.eFacility} is not in data/itemtree.json`)
  const n = (k) => Number(f[k])
  const item = ITEM_COST[id]
  out.push(
    `+Facilities=(Id=${id}, Enum=${f.eFacility}, Cash=${n('iCash')}, Elerium=${n('iElerium')}, Alloys=${n('iAlloys')}, Upkeep=${n('iMaintenance')}, ` +
      `Days=${n('iTime')}, Power=${n('iPower')}, Size=${t.size}, Multiple=${!SINGLE.includes(id)}` +
      (t.tech ? `, Tech=${t.tech.id}` : '') +
      (item ? `, Item=${itemTemplate(item[0], ITEMS)}, Items=${item[1]}` : '') +
      ')',
  )
}
out.push(
  '; The base: power, staff for labs, workshops and uplinks, satellites, digging, upkeep of the craft.',
  ...all('HQ_BASE_POWER').slice(0, 4).map((v) => `+BasePower=${v}`),
  `PowerAdjacencyBonus=${one('POWER_ADJACENCY_BONUS')}`,
  `SteamVents=${one('NUM_STARTING_STEAM_VENTS')}`,
  `LabMinimum=${one('LAB_MINIMUM')}`,
  `LabMultiple=${one('LAB_MULTIPLE')}`,
  `LabAdjacencyBonus=${one('LAB_ADJACENCY_BONUS')}`,
  `WorkshopMinimum=${one('WORKSHOP_MINIMUM')}`,
  `WorkshopMultiple=${one('WORKSHOP_MULTIPLE')}`,
  `WorkshopRebatePct=${one('WORKSHOP_REBATE_PCT')}`,
  `UplinkMultiple=${one('UPLINK_MULTIPLE')}`,
  `NexusMultiple=${one('NEXUS_MULTIPLE')}`,
  `UplinkCapacity=${one('UPLINK_CAPACITY')}`,
  `NexusCapacity=${one('NEXUS_CAPACITY')}`,
  `UplinkAdjacencyBonus=${one('UPLINK_ADJACENCY_BONUS')}`,
  `ExcavateCash=${one('BASE_EXCAVATE_CASH_COST')}`,
  `ExcavateDays=${one('BASE_EXCAVATE_DAYS')}`,
  `SkyrangerUpkeep=${one('BASE_SKYRANGER_MAINTENANCE')}`,
  // XGFacility_Hangar.GetCraftMaintenanceCost: an interceptor 40 a month (in its code, not the INI).
  'InterceptorUpkeep=40',
  // XGTechTree.OTSRank: the Officer Training School needs a soldier of this rank.
  'OTSRank=3',
  '; The hangar: an interceptor\'s price (ItemBalance_Normal), its repair, refit and transfer hours; in Long War\'s',
  '; code: 72 hours to deliver an order, 6 bays a continent, a Firestorm\'s upkeep 50.',
  `InterceptorCost=${Number(core.match(/^ItemBalance_Normal=\(eItem=eItem_Interceptor,\s*iCash=(\d+)/im)[1])}`,
  `RepairHours=${one('INTERCEPTOR_REPAIR_HOURS')}`,
  `RearmHours=${one('INTERCEPTOR_REARM_HOURS')}`,
  `TransferHours=${one('INTERCEPTOR_TRANSFER_TIME')}`,
  'OrderHours=72',
  'HangarBays=6',
  'FirestormUpkeep=50',
)
// Long War's psi powers (features/lw-psi.md), kept in ItemBalance_Easy entries that XComPerkManager.GetPerkInTreePsi
// reads as: iCash the target will, iElerium the tech that opens the power, iAlloys its tier, iEng the post-mission
// fatigue hours. Only the entries before the gene mods' (whose comment names a psi perk's tech: eTech_…).
out.push(
  "; Long War's psi training (XGFacility_PsiLabs): the chance's base, the hours (x the power's target will / the",
  "; soldier's will), the slots; and the twelve powers (Perk: Long War's perk id; TargetWill; Tech: the Long War tech",
  '; researched first, 0: specially coded; Tier; Fatigue: hours after a mission).',
  `PsiGiftChance=${one('PSI_GIFT_CHANCE')}`,
  `PsiTrainingHours=${one('PSI_TRAINING_HOURS')}`,
  `PsiSlots=${one('PSI_NUM_TRAINING_SLOTS')}`,
)
for (const m of core.matchAll(/^ItemBalance_Easy=\(eItem=(\d+),\s*iCash=(\d+),\s*iElerium=(\d+),\s*iAlloys=(\d+),\s*iTime=0,\s*iEng=(\d+)\)\s*;\s*\d+=(ePerk_\w+)/gm)) {
  out.push(`+PsiPowers=(Perk=${m[1]}, Enum=${m[6]}, TargetWill=${m[2]}, Tech=${m[3]}, Tier=${m[4]}, Fatigue=${m[5]})`)
}
// Long War's gene mods (features/lw-genemods.md): its "Gene Mod Configuration" ItemBalance_Easy entries (iCash the
// cost, iElerium the tech, iAlloys the meld, iTime the days in the tank, iEng the fatigue hours) and the slot each
// fills (XComPerkManager's GeneModPerkTree: two mods a slot, a soldier one of them).
const geneTree = core.match(/^GeneModPerkTree=\((.*)\)/m)?.[1] ?? ''
const geneSlot = new Map([...geneTree.matchAll(/(\w+?)\d=(ePerk_\w+)/g)].map((m) => [m[2], m[1]]))
out.push(
  "; Long War's gene mods (Perk: its perk id; Cash; Tech: the Long War tech researched first; Meld; Days in the tank;",
  '; Fatigue: hours after a mission; Slot: Chest, Brain, Eyes, Skin or Legs, one mod a slot).',
)
const geneAt = core.indexOf('; Gene Mod Configuration')
for (const m of core.slice(geneAt).matchAll(/^ItemBalance_Easy=\(eItem=(\d+),\s*iCash=(\d+),\s*iElerium=(\d+),\s*iAlloys=(\d+),\s*iTime=(\d+),\s*iEng=(\d+)\)\s*;\s*(ePerk_\w+)/gm)) {
  const slot = geneSlot.get(m[7])
  if (!slot) throw new Error(`gene mod ${m[7]} is in no slot of GeneModPerkTree`)
  out.push(`+GeneMods=(Perk=${m[1]}, Enum=${m[7]}, Cash=${m[2]}, Tech=${m[3]}, Meld=${m[4]}, Days=${m[5]}, Fatigue=${m[6]}, Slot=${slot})`)
}
console.log(out.join('\r\n'))
