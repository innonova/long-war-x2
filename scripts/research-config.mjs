// Long War's research as the mod's config (features/lw-research.md): LongWarX2/Config/XComLWResearch.ini.
// The techs' rules (what each requires, the research credits that cover it and the one it grants,
// what must be held before it can start) are the Long War Tech Tree's, read from Long War's
// XComStrategyGame.upk and checked against the person's saves (../xcom-ew-lw-tree/data/techtree.json);
// their time and costs are Long War's DefaultGameCore.ini TechBalance lines. Numbers only: the
// techs' names and texts are Long War's words, written on the player's machine (lw-words.mjs).
//
//   node scripts/research-config.mjs <Long War's DefaultGameCore.ini> [<the Tree's data/techtree.json>] > LongWarX2/Config/XComLWResearch.ini
import { readFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const core = readFileSync(process.argv[2], 'latin1')
const tree = JSON.parse(
  readFileSync(process.argv[3] ?? join(dirname(fileURLToPath(import.meta.url)), '..', '..', 'xcom-ew-lw-tree', 'data', 'techtree.json'), 'utf8'),
)
const lines = core.split(/\r?\n/)
const one = (key) => {
  const m = lines.map((l) => new RegExp(`^${key}\\s*=\\s*([-\\d.]+)`, 'i').exec(l)).find(Boolean)
  if (!m) throw new Error(`${key} not in the ini`)
  return Number(m[1])
}

// TechBalance=(eTech=eTech_AlienMaterials, iTime=6, iAlloys=4, …): by enum name or number.
const byEnum = new Map(tree.techs.map((t) => [t.enum, t.id]))
const balance = new Map()
for (const l of lines) {
  const m = /^TechBalance\s*=\s*\((.*)\)/.exec(l)
  if (!m) continue
  const f = Object.fromEntries(m[1].split(',').map((p) => p.split('=').map((s) => s.trim())))
  const id = /^\d+$/.test(f.eTech) ? Number(f.eTech) : byEnum.get(f.eTech)
  if (id === undefined) throw new Error(`TechBalance for an unknown tech: ${f.eTech}`)
  balance.set(id, { time: +f.iTime || 0, alloys: +f.iAlloys || 0, elerium: +f.iElerium || 0, fragments: +f.iNumFragments || 0, items: +f.iNumItems || 0 })
}

const pointsPerDay = one('TECH_TIME_BALANCE') * 72

// A picture for XCOM 2's research screen, by kind of tech: XCOM 2's own (the player has the game).
const R = (n) => `img:///UILibrary_StrategyImages.ResearchTech.${n}`
const S = (n) => `img:///UILibrary_StrategyImages.ScienceIcons.${n}`
const IMAGES = [
  [/Autopsy.*Sectoid/, S('IC_AutopsySectoid')], [/Autopsy.*Muton.*Berserker|Autopsy.*Berserker/, S('IC_AutopsyBerserker')],
  [/Autopsy.*Muton/, S('IC_AutopsyMuton')], [/Autopsy.*Chryssalid|Autopsy.*Zombie/, S('IC_AutopsyCryssalid')],
  [/Autopsy.*(Sectopod|Mechtoid|Cyberdisc|Drone)/, S('IC_AutopsySextopod')], [/Autopsy.*Floater/, S('IC_AutopsyArchon')],
  [/Autopsy.*ThinMan/, S('IC_AutopsyFaceless')], [/Autopsy.*Ethereal/, R('GOLDTECH_Avatar')], [/Autopsy/, S('IC_AutopsyAdventTrooper')],
  [/Interrogate/, R('GOLDTECH_Advent_Officer')], [/Laser|Pulse/, R('TECH_Magnetized_Weapons')], [/Gauss/, R('TECH_Gauss_Weapons')],
  [/Plasma/, R('TECH_PlasmaRifle')], [/Exp_Warfare|Weapon|Rocket|Grenade/, R('TECH_Modular_Weapons')],
  [/Armor_Archangel|Armor_Ghost|Armor_Titan|PsiArmor|Armor/, R('TECH_PlatedArmor')], [/Psi|Ethereal/, R('TECH_Psionics')],
  [/Elerium/, S('IC_Elerium')], [/AlienMaterials|Alloy/, R('TECH_Nanofiber_Materials')], [/Xenobiology|Meld|Genetic|Bio/, R('GOLDTECH_Alien_Biotech')],
  [/Hyperwave|Comm|PsiLink/, R('GOLDTECH_Resistance_Communications')], [/Firestorm|Propulsion|Navigation|UFO/, R('IC_Alien_Encryption')],
]
const imageFor = (t) => {
  if (t.id >= 61 && t.id <= 71) return R('IC_Alien_Encryption') // UFO analyses
  if (t.id >= 72 && t.id <= 75) return R(t.id === 72 ? 'TECH_PlatedArmor' : 'TECH_EXOSuit') // armour and exoskeletons
  return (IMAGES.find(([re]) => re.test(t.enum)) ?? [, R('TECH_Advent_Datapad')])[1]
}
// An array field, left out when empty: UE3's config reader stops reading a struct at "()".
const arr = (key, a) => (a && a.length ? `${key}=(${a.join(',')}), ` : '')
const items = (g) => (g ? ('any_of' in g ? g.any_of.map((i) => i.id) : [g.id]) : [])
const out = [
  "; Long War 1.0's research, generated by scripts/research-config.mjs from the Long War Tech Tree's",
  "; data/techtree.json (Long War's own rules) and Long War's DefaultGameCore.ini. Do not edit by hand.",
  '[LongWarX2.LWResearchRules]',
  `; Research points a TechBalance day is worth (TECH_TIME_BALANCE x 72: one scientist's hours).`,
  `PointsPerDay=${pointsPerDay}`,
  `StartingScientists=${one('NUM_STARTING_SCIENTISTS')}`,
  `StartingEngineers=${one('NUM_STARTING_ENGINEERS')}`,
  `LabBonus=${one('LAB_BONUS')}`,
  '; Each research credit\'s share off a covered tech (%), by credit (XGTechTree.BuildResearchCredits).',
  ...Object.entries(tree.credit_bonus).map(([k, v]) => `+CreditShare=(Credit=${k}, Percent=${v})`),
  '; Each tech: Long War\'s id and enum; the techs it requires (all), and of which one is enough; its',
  '; time in TechBalance days and costs; the credits that cover it, and the one it grants; what must',
  '; have been held (EverHad), be in stores (InStores, any of) or captured (Captured, a UFO type).',
  ...tree.techs.map((t) => {
    const b = balance.get(t.id) ?? { time: 0, alloys: 0, elerium: 0, fragments: 0, items: 0 }
    return (
      `+Techs=(Id=${t.id}, Enum=${t.enum}, ${arr('Requires', t.requires)}${arr('AnyOf', t.any_of)}Days=${b.time}, Alloys=${b.alloys}, Elerium=${b.elerium}, ` +
      `Fragments=${b.fragments}, Items=${b.items}, ${arr('Credits', t.credits)}GrantsCredit=${t.grants_credit ?? 0}, ` +
      `${arr('EverHad', items(t.ever_had))}${arr('InStores', items(t.in_stores))}${arr('Captured', items(t.captured))}Image="${imageFor(t)}")`
    )
  }),
]
console.log(out.join('\r\n'))
