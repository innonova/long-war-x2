// Long War's council requests as the mod's config (features/lw-council-requests.md): LongWarX2/Config/XComLWRequests.ini,
// from the Tree's data/requests.json (read from Long War's XGFundingCouncil.BuildRequest by scripts/upk_requests.py there)
// and the player's Long War DefaultGameCore.ini (the items' prices, for a cash reward: XGItemTree.GetItemQuestPrice).
// Numbers and template names only.
//
//   node scripts/requests-config.mjs <Long War's DefaultGameCore.ini> > LongWarX2/Config/XComLWRequests.ini
import { readFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { itemTemplate, readBalance } from './lw-gear.mjs'

const core = readFileSync(process.argv[2], 'latin1')
const treeData = (f) => JSON.parse(readFileSync(join(dirname(fileURLToPath(import.meta.url)), '..', '..', 'xcom-ew-lw-tree', 'data', f), 'utf8'))
const ITEMS = treeData('enums.json').enums.EItemType
const data = treeData('requests.json')
const balance = readBalance(core, ITEMS)
const one = (k) => Number(new RegExp(`^${k}\\s*=\\s*([-\\d.]+)`, 'm').exec(core)?.[1] ?? NaN)
// The mod's template of a requested item: alloys and elerium are XCOM 2's own (X2Item_LWArtifacts.ItemFor).
const template = (item) => (item === 161 ? 'EleriumDust' : item === 162 ? 'AlienAlloy' : itemTemplate(item, ITEMS))
// XGItemTree.GetItemQuestPrice: the item's cash, 0.065 a build hour (iTime x iEng x 24 x ITEM_TIME_BALANCE; -1 for an item
// never built), its alloys at the alloys' price (item 162's cash) and its elerium at elerium's (161's).
const hours = (b) => (b.days < 0 || b.engineers < 0 ? -1 : b.days * Math.abs(b.engineers) * 24 * one('ITEM_TIME_BALANCE'))
const questPrice = (item) => {
  const b = balance.get(item)
  if (!b) return 0
  return b.cash + Math.trunc(0.065 * hours(b)) + b.alloys * (balance.get(162)?.cash ?? 0) + b.elerium * (balance.get(161)?.cash ?? 0)
}
const amount = (r) =>
  typeof r.amount === 'number' ? `Amount=${r.amount}` : r.amount === 'corpses' ? 'AmountKind=1' : r.amount === 'fragments' ? 'AmountKind=2' : `AmountKind=3, RandN=${r.amount.rand[0]}, RandAdd=${r.amount.rand[1]}`
const reward = (w) => ('amount' in w ? `(Type=${w.type}, Fixed=${w.amount})` : `(Type=${w.type}, Min=${w.min}, Max=${w.max})`)
const c = data.constants
const out = [
  "; Long War 1.0's council requests, generated by scripts/requests-config.mjs from the Tree's data/requests.json. Do not edit by hand.",
  '[LongWarX2.LWCouncilRequests]',
  "; XGFundingCouncil.Update: a request every NextHours + rand(NextRand) hours (Quai d'Orsay: less by its share).",
  'NextHours=36',
  'NextRand=36',
  "; BuildRequest: a request's hours, RequestDays x its factor (or its own hours), less 2 per panic block of its country.",
  `RequestDays=${c.FCREQUEST_DAYS}`,
  '; CreateReward: a cash reward is the item\'s quest price (+ the reward\'s minimum when it is not 1) x the amount x ProfitMargin.',
  `ProfitMargin=${c.PROFIT_MARGIN}`,
  "; Requests (EFCRequest): Item (EItemType) and its Template, Requires (ETechType, all researched), Amount, or AmountKind",
  '; 1 corpses (GetNumberOfCorpsesToSell: (1 + rand 4) x month, 6 to 20), 2 fragments ((2 + rand 4) x month, 12 to 50),',
  '; 3 rand(RandN) + RandAdd; HoursFactor or Hours; Transfer 1 a satellite over the country, 2 a jet to its continent;',
  '; Price: the item\'s quest price; Alts: one per branch of Long War\'s roll, each its rewards (EFCRewardType: 1 cash,',
  '; 2 a soldier or scientists, 3 a soldier, 4 scientists, 5 engineers, 6 panic; Min and Max for CreateReward, Fixed as given).',
  ...data.requests.map((r) =>
    `+Requests=(Id=${r.id}, Item=${r.item}, Template=${template(r.item)}, ${r.requires?.length ? `Requires=(${r.requires.join(',')}), ` : ''}${amount(r)}, ` +
    `${r.hours ? `Hours=${r.hours}` : `HoursFactor=${r.hoursFactor}`}, Transfer=${r.transfer === 'satellite' ? 1 : r.transfer === 'jet' ? 2 : 0}, ` +
    `Price=${questPrice(r.item)}, Alts=(${r.rewards.map((a) => `(Rewards=(${a.map(reward).join(', ')}))`).join(', ')}))`),
]
console.log(out.join('\r\n'))
