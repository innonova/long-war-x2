// Long War's SHIVs as the mod's config (features/lw-shivs-mecs.md): LongWarX2/Config/XComLWSHIVs.ini, from the player's
// Long War DefaultGameCore.ini: the SHIV's own stats (Characters, eChar_Tank), each body's deck (Armors, eItem_SHIVDeck_I to
// III) and the hit points it needs repaired (ALLOY_SHIV_HP_BONUS, HOVER_SHIV_HP_BONUS), the SHIV weapons (Weapons=), the
// repair time (BASE_DAYS_INJURED_TANK). Numbers only.
//
//   node scripts/shivs-config.mjs <Long War's DefaultGameCore.ini> > LongWarX2/Config/XComLWSHIVs.ini
import { readFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const core = readFileSync(process.argv[2], 'latin1')
const ITEMS = JSON.parse(readFileSync(join(dirname(fileURLToPath(import.meta.url)), '..', '..', 'xcom-ew-lw-tree', 'data', 'enums.json'), 'utf8')).enums.EItemType
const itemId = (e) => {
  const i = ITEMS.findIndex((x) => x.toLowerCase() === e.toLowerCase())
  if (i < 0) throw new Error(`no item ${e}`)
  return i
}
const fields = (line) => Object.fromEntries(line.split(',').filter((p) => p.includes('=')).map((p) => p.split('=').map((s) => s.trim())))
// An item's damage reduction: BalanceMods_Classic's iHP, in tenths (as gear-config.mjs reads it for armours).
const itemDR = (id) => Number(core.match(new RegExp(`^BalanceMods_Classic=\\(eType=${id},.*?iHP=(-?\\d+)`, 'm'))?.[1] ?? 0) / 10
const one = (k) => Number(core.match(new RegExp(`^${k}\\s*=\\s*(-?[\\d.]+)`, 'm'))[1])
const tank = fields(core.match(/^Characters=\((.*iType=eChar_Tank\b.*)\)/m)[1])
const deck = (e) => fields(core.match(new RegExp(`^Armors=\\((.*iType=${e}\\b.*)\\)`, 'm'))[1])
const weapon = (e) => fields(core.match(new RegExp(`^Weapons=\\((.*iType=${e}\\b.*)\\)`, 'mi'))[1])

// Long War's three bodies (built in engineering) and the deck each wears.
const BODIES = [
  { body: 'eItem_SHIV', template: 'LWSHIV', enum: 'eItem_SHIVDeck_I', repair: 0 },
  { body: 'eItem_SHIV_Alloy', template: 'LWSHIV_Alloy', enum: 'eItem_SHIVDeck_II', repair: one('ALLOY_SHIV_HP_BONUS') },
  { body: 'eItem_SHIV_Hover', template: 'LWSHIV_Hover', enum: 'eItem_SHIVDeck_III', repair: one('HOVER_SHIV_HP_BONUS') },
].map((b) => ({ ...b, item: itemId(b.body), deck: itemId(b.enum) }))
const WEAPONS = [
  { enum: 'eItem_ShivMinigun', template: 'LWSHIV_Minigun' },
  { enum: 'eItem_ShivSentry', template: 'LWSHIV_Sentry' },
  { enum: 'eItem_ShivLaser', template: 'LWSHIV_Laser' },
  { enum: 'eItem_ShivPlasma', template: 'LWSHIV_Plasma' },
].map((w) => ({ ...w, item: itemId(w.enum) }))
const out = [
  "; Long War 1.0's SHIVs, generated by scripts/shivs-config.mjs from Long War's DefaultGameCore.ini. Do not edit by hand.",
  '[LongWarX2.LWSHIVs]',
  '; The SHIV (eChar_Tank); RepairHours: a wounded SHIV\'s base time in repair (BASE_DAYS_INJURED_TANK).',
  `Base=(HP=${tank.HP}, Aim=${tank.Offense}, Defense=${tank.Defense}, Mobility=${tank.Mobility}, Sight=${tank.SightRadius})`,
  `RepairHours=${one('BASE_DAYS_INJURED_TANK')}`,
  // Numbers of Long War's code (XGFacility_Barracks.DetermineTimeOut), not its config: a SHIV back from a mission is out
  // RestHours plus up to RestRollHours; a damaged one, RepairHours per hit point lost, twice that per point below a quarter,
  // plus up to half of that (at least RepairRollMin); two thirds of it once the Foundry's RepairFoundry is done.
  '; Rest and repair (Long War\'s code): RestHours + Rand(RestRollHours); RepairHours per HP lost, twice that per HP below a',
  '; quarter, + Rand(max(half, RepairRollMin)); x RepairFoundryScale with the Foundry\'s RepairFoundry (Vehicle Repair).',
  'RestHours=24',
  'RestRollHours=24',
  'RepairRollMin=96',
  'RepairFoundry=5',
  'RepairFoundryScale=0.67',
  '; Bodies: Item, the character Template, its Deck (item) and the deck\'s HP, Defense, Mobility, SmallItems, Fly and Fuel;',
  '; RepairHP: hit points beyond the deck\'s that repair restores (Long War\'s "base hp bonuses that require repair");',
  '; DR: the deck\'s damage reduction (BalanceMods_Classic\'s iHP, in tenths).',
  ...BODIES.map((b) => {
    const d = deck(b.enum)
    const fly = /eAbility_Fly/.test(d.ABILITIES ?? '') || Object.values(d).includes('eAbility_Fly')
    return `+Bodies=(Item=${b.item}, Template=${b.template}, Deck=${b.deck}, HP=${d.iHPBonus}, Defense=${d.iDefenseBonus}, Mobility=${d.iMobilityBonus}, ` +
      `SmallItems=${d.iSmallItems}, Fly=${fly}, Fuel=${d.iFlightFuel}, RepairHP=${b.repair}, DR=${itemDR(b.deck)})`
  }),
  '; Weapons: Damage, Crit, Aim, Environment; Ammo: shots between reloads (iSuppression\'s last two digits).',
  ...WEAPONS.map((w) => {
    const f = weapon(w.enum)
    return `+Weapons=(Item=${w.item}, Enum=${w.enum}, Template=${w.template}, Damage=${f.iDamage}, Crit=${f.iCritical}, Aim=${f.iOffenseBonus}, ` +
      `Environment=${f.iEnvironmentDamage}, Ammo=${Number(f.iSuppression) % 100})`
  }),
]
console.log(out.join('\r\n'))
