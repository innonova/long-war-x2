// Long War 1.0's air war data as the mod's config (LongWarX2/Config/XComLWAirWar.ini):
// ships, weapons, how UFOs change as the aliens advance, and which UFOs crash
// rather than break up. From the Long War Tech Tree's data/airwar.json (read
// there from Long War's own DefaultGameCore.ini and script), with the base
// values and their growth per category; Foundry projects and Friendly Skies
// are not carried yet (features/hard-parts.md, experiment 3).
//
//   node scripts/airwar-config.mjs <xcom-ew-lw-tree>/data/airwar.json > LongWarX2/Config/XComLWAirWar.ini
import { readFileSync } from 'node:fs'

const air = JSON.parse(readFileSync(process.argv[2], 'utf8'))
const v = (s) => s?.base ?? 0
const per = (s) => s?.per_category ?? 0
const q = (s) => `"${String(s).replace(/"/g, "'")}"`
const list = (a) => `(${a.join(',')})`

const out = [
  '; Long War 1.0\'s air war, generated by scripts/airwar-config.mjs from the Long War Tech',
  '; Tree\'s data/airwar.json. Do not edit by hand: change the generator or its source.',
  '[LongWarX2.LWAirWar]',
]
for (const w of air.weapons)
  out.push(`+Weapons=(Id=${w.id}, Name=${q(w.name)}, FiringTime=${v(w.firing_time)}, Damage=${v(w.damage)}, DamagePerCategory=${per(w.damage)}, Ap=${v(w.ap)}, ToHit=${v(w.to_hit)}, ToHitPerCategory=${per(w.to_hit)})`)
for (const s of air.ships) {
  if (s.weapons.length === 0) continue // the Skyranger does not fight
  const k = air.destroy_divisor[String(s.id)] ?? 0
  out.push(`+Ships=(Id=${s.id}, Name=${q(s.name)}, Size=${q(s.size)}, BattleSpeed=${v(s.battle_speed)}, Hp=${v(s.hp)}, HpPerCategory=${per(s.hp)}, Armor=${v(s.armor)}, Ap=${v(s.ap)}, Weapons=${list(s.weapons)}, DestroyDivisor=${k}, AlwaysCrash=${air.always_crash.includes(s.id)})`)
}
for (const c of air.ufo_changes) {
  const st = c.stats
  const stats = st
    ? `, HasStats=true, BattleSpeed=${v(st.battle_speed)}, Hp=${v(st.hp)}, HpPerCategory=${per(st.hp)}, Armor=${v(st.armor)}, Ap=${v(st.ap)}`
    : ''
  out.push(`+UfoChanges=(Ship=${c.ship}, AboveCategory=${c.above_category}${c.weapons ? `, Weapons=${list(c.weapons)}` : ''}${c.size ? `, Size=${q(c.size)}` : ''}${stats})`)
}
console.log(out.join('\r\n'))
